'use strict';
const assert = require('node:assert/strict');
const { loadFixture, validate, PIN_PATTERN, TEST_MARKER } = require('./location-validator');

const fixture = loadFixture();
const result = validate(fixture);

assert.equal(fixture.fixture_metadata.data_status, TEST_MARKER);
assert.equal(fixture.fixture_metadata.authoritative, false);
assert.ok(PIN_PATTERN.test('324005'));
assert.ok(!PIN_PATTERN.test('32405'));
assert.ok(!PIN_PATTERN.test('324005A'));
const indiaPinFixture = JSON.parse(JSON.stringify(fixture));
indiaPinFixture.pincodes[0].code = '32405A';
assert.ok(validate(indiaPinFixture).rejected.some(record => record.reason.includes('invalid Indian PIN format')));
const nonIndiaFixture = JSON.parse(JSON.stringify(fixture));
nonIndiaFixture.countries[0].iso2_code = 'XX';
nonIndiaFixture.pincodes[0].code = 'AB-123';
assert.ok(validate(nonIndiaFixture).accepted.some(record => record.record_type === 'pincodes' && record.record_id === nonIndiaFixture.pincodes[0].id));
assert.ok(result.accepted.length > 0, 'valid synthetic records should be accepted');
assert.ok(result.rejected.some(record => record.record_id === 'invalid-locality-district-mismatch'));
assert.ok(result.rejected.some(record => record.record_id === 'invalid-post-office-pincode-mismatch'));
assert.ok(result.ambiguous.some(record => record.record_id === 'Unknown Kota Area'));
assert.equal(fixture.localities.some(record => record.name === 'Unknown Kota Area'), false);
assert.equal(result.accepted.some(record => record.record_type === 'legacy_kota_mapping' && record.record_id === 'Unknown Kota Area'), false);
assert.ok(result.summary.rejected_count > 0);
assert.ok(result.summary.ambiguous_count > 0);
const duplicateFixture = JSON.parse(JSON.stringify(fixture));
duplicateFixture.localities.push({ ...duplicateFixture.localities[0], id: '00000000-0000-0000-0000-000000009999' });
const duplicateResult = validate(duplicateFixture);
assert.ok(duplicateResult.rejected.some(record => record.reason === 'duplicate location'));
assert.equal(duplicateResult.accepted.some(record => record.record_type === 'localities' && record.record_id === '00000000-0000-0000-0000-000000009999'), false);
const lifecycleFixture = JSON.parse(JSON.stringify(fixture));
lifecycleFixture.localities[0].is_active = false;
lifecycleFixture.localities[1].merged_into_id = 'missing-target';
lifecycleFixture.localities[2].merged_into_id = lifecycleFixture.localities[3].id;
lifecycleFixture.localities[3].merged_into_id = lifecycleFixture.localities[2].id;
const lifecycleResult = validate(lifecycleFixture);
assert.ok(lifecycleResult.rejected.some(record => record.reason === 'inactive location cannot be accepted as active import'));
assert.ok(lifecycleResult.rejected.some(record => record.reason === 'invalid merge target'));
assert.ok(lifecycleResult.rejected.some(record => record.reason === 'merge cycle detected'));
assert.equal(lifecycleResult.accepted.some(record => record.record_type === 'localities' && record.record_id === lifecycleFixture.localities[0].id), false);
assert.equal(result.summary.authoritative, false);
console.log(`Isolated location validator tests passed: ${result.summary.accepted_count} accepted, ${result.summary.rejected_count} rejected, ${result.summary.ambiguous_count} ambiguous`);
